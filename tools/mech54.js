F.performAction(knock,'ult',knock.kit.ult);
ok('大警報: デバフを1つだけ解除し、免疫を付け直す', ((giant.buffs.healCut?1:0)+(giant.buffs.vuln?1:0))===1 && B.party.every(u=>u.buffs.ward));
const hp0=api.MON_BY_ID.m51.hp;
ok('ヒルジャイアント: 最大HP+10%', giant.maxHp>=Math.round(giant.maxHp/1.1*1.1)-1 && giant.maxHp>Math.round(giant.maxHp/1.1), giant.maxHp);
const s0=F.effStr(kyon);
kyon.hp=Math.round(kyon.maxHp*0.45); F.hitHp(kyon,1,e,{});
ok('キョンシー: HP50%を下回ると札が外れる(STR-20%→+40%)', kyon.flags.unsealed && F.effStr(kyon)>s0*1.6, [s0, F.effStr(kyon)]);
kyon.hp=kyon.maxHp;
ok('キョンシー: 回復しても札は外れたまま', kyon.flags.unsealed && F.effSpd(kyon)===kyon.spd+15);
kappa.hp=Math.round(kappa.maxHp*0.55); giant.hp=10;
F.hitHp(kappa,Math.round(kappa.maxHp*0.1),e,{});
ok('河童: HP50%を下回ったら1度だけ味方全員を回復', giant.hp>10 && kappa.flags.dishUsed, giant.hp);
F.applyStatus(e,'burn',hino); const eh=e.hp; const r=hit(hino,e,1,'mag');
