let knock=U(B,'m48'), kyon=U(B,'m96'), kappa=U(B,'m117'), giant=U(B,'m51'), hino=U(B,'m129'), e=B.enemies[0];
ok('ノッカー: 戦闘開始時に味方全員へ免疫', B.party.every(u=>u.buffs.ward));
F.applyStatus(kyon,'burn',e);
ok('免疫: 状態異常を1回防いで消える', !kyon.statuses.burn && !kyon.buffs.ward);
F.applyStatus(kyon,'burn',e);
ok('免疫が消えたあとはかかる', !!kyon.statuses.burn);
F.applyDebuff(kappa,'strDown',0.2,2,e);
ok('免疫: デバフも防ぐ', !kappa.buffs.strDown && !kappa.buffs.ward);
kappa.sp=50; F.addBuff(kappa,'ward',1,3,knock); api.STATE; // SP drain isn't blocked
F.strike({actor:e,act:{atk:'phys',onHit:[{drain:10}]},kind:'skill'}, kappa, {pow:0.01});
ok('免疫: SP減少は防がない', kappa.sp<=45 && kappa.buffs.ward, kappa.sp);
const c0=F.cutOf(giant,'phys'); F.addBuff(giant,'vuln',0.2,2,e);
