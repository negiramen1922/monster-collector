const load=require('./harness.js');
const api=load('game.js', src => src + `;global.__f={applyStatus,strike,hitHp,healUnit,startTurn,performAction,applyDebuff,addBuff,cutOf,effStr,effSpd,killUnit,shieldTotal,get b(){return battleUI}};`);
const F=global.__f;
const ok=(name, cond, info)=>console.log((cond?'✅':'❌')+' '+name+(info!==undefined?'  '+JSON.stringify(info):''));
function setup(party){
  api.run([], 'q1_01', 1);
  const S=api.STATE; S.owned={};
  party.forEach(id=>S.owned[id]={star:Math.max(4,api.MON_BY_ID[id].rarity),souls:0,level:30,exp:0,wall:30,skillLv:1,ultLv:1,passiveLv:1});
  S.formationKey='f2'; S.slots=api.lineupFromList(party,'f2'); S.clearedStages=api.STAGES.map(s=>s.id);
  api.startBattle('q1_01',{skipIntro:true});
  const B=F.b; B.transitioning=false; B.paused=true;
  B.enemies.forEach(e=>{ e.maxHp=e.hp=99999; e.str=60; e.pdef=0; e.mdef=0; e.alive=true; });
  B.enemies.slice(1).forEach(e=>{ e.alive=false; });
  return B;
}
const U=(B,id)=>B.party.find(u=>u.ref===id);
const hit=(atk,t,pow,type)=>F.strike({actor:atk,act:{atk:type||'phys'},kind:'normal'}, t, {pow});
